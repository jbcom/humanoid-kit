/** A community garment: where it is, what its page says, and how it is worn. */
export interface CommunityGarment {
  /** The pack it comes in (`COMMUNITY_CLOTHING_PACKS`). */
  pack: string;
  /** Its directory under the pack's `clothes/`, which is its asset name. */
  dir: string;
  kind: keyof typeof GARMENT_LAYERS;
  label: string;
  page: CommunityPage;
}

/** The date the pages were read. */
